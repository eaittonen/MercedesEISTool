using System;
using System.Linq;
using MercedesEISTool.Server.Services;

var service = new KeyFileAnalysisService();
var keyData = new byte[160];
keyData[0x00] = 0x01;
keyData[0x01] = 0x5F;
keyData[0x02] = 0xC1;
keyData[0x03] = 0x4A;
keyData[0x04] = 0xA7;
keyData[0x05] = 0xA5;
keyData[0x06] = 0xBF;
keyData[0x07] = 0x71;
keyData[0x08] = 0xE5;
keyData[0x09] = 0x01;
keyData[0x0A] = 0x00;
keyData[0x0B] = 0x4C;
keyData[0x0C] = 0xB2;
keyData[0x0D] = 0xFC;
var keySlotBytes = new byte[] { 0xAF, 0x66, 0x54, 0x0E, 0x03, 0x13, 0x9B, 0x5C };
Array.Copy(keySlotBytes, 0, keyData, 0x73, keySlotBytes.Length);
Array.Copy(new byte[] { 0x00, 0x4C, 0xB2, 0xFC }, 0, keyData, 0x8C, 4);
var eisData = new byte[256];
Array.Copy(new byte[] { 0xAF, 0x66, 0x54, 0x0E, 0x03, 0x13, 0x9B, 0x5C }, 0, eisData, 0x80 + 8, 8);
Array.Copy(new byte[] { 0x00, 0x4C, 0xB2, 0xFC }, 0, eisData, 0x80 + 0x0C, 4);
var result = service.AnalyzeAndAssociate(keyData, eisData, "x");
Console.WriteLine($"status={result.AssociationStatus}");
Console.WriteLine($"keyIndex={result.KeyIndex}");
Console.WriteLine($"slotNumber={result.SlotNumber}");
Console.WriteLine($"ssid={result.Ssid}");
Console.WriteLine($"slotBytes={BitConverter.ToString(keyData.Skip(0x73).Take(8).ToArray())}");
Console.WriteLine($"readSlot={BitConverter.ToString(eisData.Skip(0x80 + (result.KeyIndex ?? 0) * 8).Take(8).ToArray())}");
Console.WriteLine($"readSsid={BitConverter.ToString(eisData.Skip(0x80 + 0x0C).Take(4).ToArray())}");
